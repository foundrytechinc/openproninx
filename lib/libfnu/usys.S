#include "inc/syscall.h"

#define T_SYSCALL 0x30

# THE SYSTEM'S OWN CALLS. The number goes in rax; the carry flag says rax came
# back an error number, and the stub returns its negative. Nothing here writes
# a global: errno belongs to the POSIX module, not to the system
#define SYSCALL(name) \
  .globl fnu_ ## name; \
  fnu_ ## name: \
    mov $SYS_ ## name, %rax; \
    int $T_SYSCALL; \
    jnc 8f; \
    neg %rax; \
8:  ret

