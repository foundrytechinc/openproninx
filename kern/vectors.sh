#!/bin/sh
# vectors.S: one entry per interrupt

set -eu

echo "# generated by vectors.sh - do not edit"
echo "# handlers"
echo ".globl alltraps"
echo ".globl alltraps_ist"

i=0
while [ $i -lt 256 ]; do
	echo ".globl vector$i"
	echo "vector$i:"
	case $i in
	8|10|11|12|13|14|17) ;;
	*) echo "  pushq \$0" ;;
	esac
	echo "  pushq \$$i"
	case $i in
	1|2|8|18) echo "  jmp alltraps_ist" ;;
	*) echo "  jmp alltraps" ;;
	esac
	i=$((i + 1))
done

echo ""
echo "# vector table"
echo ".data"
echo ".globl vectors"
echo "vectors:"

i=0
while [ $i -lt 256 ]; do
	echo "  .quad vector$i"
	i=$((i + 1))
done
